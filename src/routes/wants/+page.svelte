	<h2 id="pressing">First: the pressing kit — the real gap</h2>
	<p>
		Pressing is roughly half of tailoring, and a weak iron physically cannot shape wool. Everything in this section
		outranks any notion or gadget:
	</p>
	<ul>
		<li>
			<strong>Tailoring steam iron</strong> — Rowenta DW5280 Steamforce / DW8080 Pro Master class (~$90–120), or a gravity-feed
			/ steam-generator station if the budget stretches (~$200–300).
		</li>
		<li>
			<strong>Sturdy wide board or pressing table + wool pressing mat</strong> — a firm, heat-stable surface (~$60–90 board
			+ ~$30–45 mat).
		</li>
		<li>
			<strong>Tailor's ham + seam/sleeve roll</strong> — presses curved darts and sleeve caps into a 3-D shape instead of
			flattening them.
		</li>
		<li>
			<strong>Sleeve board</strong> (~$25) and a <strong>wooden clapper / point-presser</strong> (~$15–25) —
			cooling-under-pressure is what <em>sets</em> wool.
		</li>
		<li><strong>Press cloth</strong> (silk organza + cotton) — mandatory on wool, dark and fused fabric.</li>
	</ul>

	<h2 id="edge">Edge-finishing</h2>
	<ul>
		<li>
			<strong>Pinking shears or a pinking-blade rotary head</strong> — the only quick no-serger fray-resist edge besides
			a hand overcast or a Hong-Kong bind (a straight rotary blade does <em>not</em> pink).
		</li>
		<li>
			<strong>Serger / overlocker</strong> (Singer/Babylock class) — fast, durable one-pass edge-finishing on shirting and
			lining seams. A want rather than a blocker: pinking, turn-and-stitch, or a Hong-Kong bind covers the gap until one lands.
		</li>
	</ul>

	<h2 id="consumables">Small stuff that matters</h2>
	<ul>
